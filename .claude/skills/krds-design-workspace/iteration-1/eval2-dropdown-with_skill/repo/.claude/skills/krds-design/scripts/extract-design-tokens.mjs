#!/usr/bin/env node
/**
 * Regenerates references/design-tokens.md from an installed krds-react package's compiled CSS.
 *
 * krds-react doesn't publish a separate design-tokens package — the ~1800 `--krds-*` custom
 * properties only exist inside dist/index.css (minified to one line). This script parses the
 * `:root { ... }` block, groups the tokens by category (color scales, typography, radius,
 * elevation, etc.), and writes a readable markdown table so a redesign task can look up a hex
 * value or font-size without grepping a minified CSS file by hand.
 *
 * Run this after bumping the krds-react version:
 *
 *   node .claude/skills/krds-design/scripts/extract-design-tokens.mjs [projectRoot]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = process.argv[2] ?? process.cwd();
const cssPath = join(projectRoot, "node_modules/krds-react/dist/index.css");
const pkgJsonPath = join(projectRoot, "node_modules/krds-react/package.json");
const skillDir = dirname(dirname(fileURLToPath(import.meta.url)));
const outPath = join(skillDir, "references/design-tokens.md");

let version = "unknown";
let css;
try {
  version = JSON.parse(readFileSync(pkgJsonPath, "utf8")).version;
  css = readFileSync(cssPath, "utf8");
} catch {
  console.error(
    `krds-react not found under ${projectRoot}/node_modules — run "npm install krds-react" first.`,
  );
  process.exit(1);
}

const rootMatch = css.match(/:root\{(.*?)\}/s);
if (!rootMatch) {
  console.error("Could not find a :root{...} block in dist/index.css.");
  process.exit(1);
}
const tokens = new Map();
for (const m of rootMatch[1].matchAll(/(--krds-[a-zA-Z0-9-]+):\s*([^;]+);/g)) {
  tokens.set(m[1], m[2].trim());
}

function section(title, predicate, note) {
  const rows = [...tokens.entries()].filter(([k]) => predicate(k));
  if (rows.length === 0) return "";
  const noteLine = note ? `${note}\n\n` : "";
  const body = rows
    .map(([k, v]) => `| \`${k}\` | \`${v}\` |`)
    .join("\n");
  return `## ${title}\n\n${noteLine}| Token | Value |\n| --- | --- |\n${body}\n\n`;
}

const doc =
  `<!-- AUTO-GENERATED by extract-design-tokens.mjs against krds-react@${version}. Do not hand-edit; rerun the script instead. -->\n\n` +
  `# krds-react global design tokens (v${version})\n\n` +
  `These are the \`:root\`-scoped custom properties from \`node_modules/krds-react/dist/index.css\` ` +
  `— the actual color/typography/spacing values behind every component. Prefer a krds-react ` +
  `component over hand-rolling styles from these tokens (see SKILL.md), but when you must style ` +
  `custom markup (a page background, a section that has no matching component) to look ` +
  `KRDS-native, pull the color/spacing from here rather than guessing a hex value or Tailwind ` +
  `default.\n\n` +
  `There are ~1800 tokens total; this file lists the global/semantic ones. Component-scoped ` +
  `tokens (e.g. \`--krds-badge--color-primary-text\`) live directly in each component's CSS and ` +
  `are enumerated in \`component-catalog.md\` implicitly — style via the component's own props ` +
  `instead of overriding those.\n\n` +
  section(
    "Color scales (light theme)",
    (k) => /^--krds-color-light-(primary|secondary|gray|alpha)-/.test(k),
    "Each color is a 0–100 scale (5 = lightest tint, 95 = darkest shade); `primary` is KRDS blue, `secondary` is a muted blue-gray accent.",
  ) +
  section(
    "Color scales (high-contrast / accessible mode)",
    (k) => /^--krds-color-high-contrast-/.test(k),
    "Used when the user enables KRDS's 선명한 화면 모드 (high-contrast display mode) — see `HighContrastToggle` usage patterns in SKILL.md.",
  ) +
  section(
    "Typography — desktop font sizes",
    (k) => k.startsWith("--krds-pc-font-size-"),
  ) +
  section(
    "Typography — mobile font sizes",
    (k) => k.startsWith("--krds-mobile-font-size-"),
  ) +
  section(
    "Typography — family / weight / letter-spacing",
    (k) => k.startsWith("--krds-typo-") || k.startsWith("--krds-font-"),
  ) +
  section("Border radius", (k) => k.startsWith("--krds-radius-")) +
  section(
    "Base numeric scale (used by radius/spacing tokens above)",
    (k) => /^--krds-number-\d+$/.test(k),
  );

writeFileSync(outPath, doc);
console.log(`Wrote ${outPath} (${tokens.size} root tokens scanned, krds-react@${version})`);
