#!/usr/bin/env node
/**
 * Regenerates references/component-catalog.md from an installed krds-react package.
 *
 * krds-react ships full .d.ts files per component but no single prop-reference doc, so this
 * script walks node_modules/krds-react/dist/components/*, pulls out each component's
 * `*.types.d.ts` (falling back to the main `.d.ts` when no separate types file exists), and
 * concatenates them into one browsable markdown file grouped by component name.
 *
 * Run this after bumping the krds-react version so the bundled reference doesn't drift from
 * what's actually installed:
 *
 *   node .claude/skills/krds-design/scripts/extract-component-catalog.mjs [projectRoot]
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = process.argv[2] ?? process.cwd();
const componentsDir = join(
  projectRoot,
  "node_modules/krds-react/dist/components",
);
const pkgJsonPath = join(projectRoot, "node_modules/krds-react/package.json");
const skillDir = dirname(dirname(fileURLToPath(import.meta.url)));
const outPath = join(skillDir, "references/component-catalog.md");

let version = "unknown";
try {
  version = JSON.parse(readFileSync(pkgJsonPath, "utf8")).version;
} catch {
  console.error(
    `krds-react not found at ${pkgJsonPath} — run "npm install krds-react" first.`,
  );
  process.exit(1);
}

const entries = readdirSync(componentsDir).filter((name) =>
  statSync(join(componentsDir, name)).isDirectory(),
);
entries.sort();

const sections = entries.map((name) => {
  const dir = join(componentsDir, name);
  const files = readdirSync(dir);
  const typesFile =
    files.find((f) => f.endsWith(".types.d.ts")) ??
    files.find((f) => f.endsWith(".d.ts") && !f.endsWith("index.d.ts"));
  if (!typesFile) return `## ${name}\n\n(no .d.ts found)\n`;
  const content = readFileSync(join(dir, typesFile), "utf8")
    .replace(/\/\/# sourceMappingURL.*$/m, "")
    .trim();
  return `## ${name}\n\n\`\`\`ts\n${content}\n\`\`\`\n`;
});

const header = `<!-- AUTO-GENERATED by extract-component-catalog.mjs against krds-react@${version}. Do not hand-edit; rerun the script instead. -->

# krds-react component prop reference (v${version})

Full prop types for every component, pulled directly from the installed package's \`.d.ts\`
files. When in doubt about a prop name, check here first instead of guessing — krds-react's
own component names (\`Dropdown\`, \`Select\`) can be misleading (see SKILL.md's "Dropdown vs
Select" gotcha).

`;

writeFileSync(outPath, header + sections.join("\n"));
console.log(`Wrote ${outPath} (${entries.length} components, krds-react@${version})`);
